#!/usr/bin/env python3
"""Tier-0 heterogeneity screen — PANNs top-10 event recall per requested event (CPU).

Evaluates the audio generated by `tier0_screening.py` for {base, P0-std, P1-nat}. The v4
PRIMARY event metric is PANNs top-10 recall per requested event (Singh et al. 2026
compatible): for each generated clip and its prompt's requested AudioSet event(s), the
event is "captured" iff its class index is in the clip's PANNs Cnn14 top-10.

Per event e and system S: `recall_S(e)` = fraction of e's prompts where e is captured;
per-event loss `L_S(e) = recall_base(e) − recall_S(e)`. The Tier-0 heterogeneity screen
(plan §6) reports: the between-event dispersion of `L(e)` (with a prompt-bootstrap CI) and
`Spearman(L_{P0-std}, L_{P1-nat})` — its only role is to inform DECISION-V4-02 (fund Tier 1
or not). **Screening only; NOT Gate E** (Tier 0 has no RAND audio).

    .venv/bin/python scripts/research/tier0_screen_eval.py \
        --screen-root artifacts/tier0_screening --out artifacts/tier0_screening/screen_eval.json
"""
from __future__ import annotations

import argparse
import csv
import glob
import json
import os
import sys

import numpy as np

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from panns_topk import build_cnn14  # noqa: E402

SCREEN_PROMPTS = "configs/research/prompts_heterogeneity_screen.json"
CSV_PATH = "data/dataset/metadata/audiocaps/class_labels_indices.csv"
MIN_PROMPTS_PER_EVENT = 5   # events with fewer prompts have unstable recall; reported separately


def load_mid_to_index():
    mid2idx, idx2name = {}, {}
    for r in csv.DictReader(open(CSV_PATH)):
        mid2idx[r["mid"]] = int(r["index"])
        idx2name[int(r["index"])] = r["display_name"]
    return mid2idx, idx2name


def latest_gen_dir(system_dir):
    hits = sorted(glob.glob(os.path.join(system_dir, "gen", "infer_*")))
    hits = [h for h in hits if os.path.isdir(h)]
    return hits[-1] if hits else None


def top10_per_clip(gen_dir, k=10):
    """Return {wav_id: set(top-k class indices)} for every wav in gen_dir."""
    import librosa
    import torch
    model = build_cnn14(); model.eval()
    out = {}
    for name in sorted(f for f in os.listdir(gen_dir) if f.lower().endswith(".wav")):
        wav, _ = librosa.load(os.path.join(gen_dir, name), sr=16000, mono=True)
        x = torch.tensor(wav, dtype=torch.float32).unsqueeze(0)
        with torch.no_grad():
            probs = model(x)["clipwise_output"].squeeze(0).cpu().numpy()
        wav_id = os.path.splitext(name)[0]
        out[wav_id] = set(int(i) for i in np.argsort(probs)[::-1][:k])
    return out


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--screen-root", default="artifacts/tier0_screening")
    ap.add_argument("--prompts", default=SCREEN_PROMPTS)
    ap.add_argument("--k", type=int, default=10)
    ap.add_argument("--n-boot", type=int, default=2000)
    ap.add_argument("--out", default=None)
    args = ap.parse_args()

    mid2idx, idx2name = load_mid_to_index()
    prompts = json.load(open(args.prompts))["prompts"]
    # wav_id -> requested event mids (that are real AudioSet classes)
    req = {os.path.splitext(os.path.basename(p["wav"]))[0]:
           [m for m in p.get("requested_events", []) if m in mid2idx] for p in prompts}

    systems = [d for d in ("base", "P0-std", "P1-nat")
               if os.path.isdir(os.path.join(args.screen_root, d))]
    if "base" not in systems:
        print("FATAL: base generation missing", file=sys.stderr); return 2

    # top-10 per clip per system
    captured = {}   # system -> {wav_id: set(idx)}
    for s in systems:
        gd = latest_gen_dir(os.path.join(args.screen_root, s))
        if gd is None:
            print(f"WARN: no gen dir for {s}"); continue
        captured[s] = top10_per_clip(gd, args.k)
        print(f"{s}: classified {len(captured[s])} clips ({gd})")

    # occurrences: (wav_id, event mid) where the clip exists for base
    occ = [(w, m) for w, mids in req.items() for m in mids if w in captured["base"]]
    events = sorted({m for _, m in occ})

    def recall(system, e):
        ws = [w for (w, m) in occ if m == e and w in captured.get(system, {})]
        if not ws:
            return None, 0
        hits = sum(1 for w in ws if mid2idx[e] in captured[system][w])
        return hits / len(ws), len(ws)

    per_event = {}
    for e in events:
        rb, nb = recall("base", e)
        row = {"event": idx2name[mid2idx[e]], "n_prompts": nb, "recall_base": rb}
        for s in systems:
            if s == "base":
                continue
            rs, _ = recall(s, e)
            row[f"recall_{s}"] = rs
            row[f"L_{s}"] = (rb - rs) if (rb is not None and rs is not None) else None
        per_event[e] = row

    # heterogeneity screen on events with enough prompts
    strong = [e for e in events if per_event[e]["n_prompts"] >= MIN_PROMPTS_PER_EVENT]
    result = {"systems": systems, "k": args.k, "n_events": len(events),
              "n_events_ge_min": len(strong), "min_prompts_per_event": MIN_PROMPTS_PER_EVENT,
              "per_event": per_event, "screen": {}}

    from scipy.stats import spearmanr
    rng = np.random.default_rng(20260818)
    for s in systems:
        if s == "base":
            continue
        L = np.array([per_event[e][f"L_{s}"] for e in strong
                      if per_event[e].get(f"L_{s}") is not None])
        if L.size >= 3:
            # prompt-bootstrap CI of the between-event dispersion (std of L over events)
            boots = np.array([np.std(rng.choice(L, size=L.size, replace=True)) for _ in range(args.n_boot)])
            result["screen"][s] = {
                "mean_L": float(L.mean()), "between_event_std_L": float(L.std()),
                "dispersion_ci95": [float(np.percentile(boots, 2.5)), float(np.percentile(boots, 97.5))],
                "n_events": int(L.size),
            }
    # Spearman between P0-std and P1-nat per-event loss (pattern stability across criteria)
    if "P0-std" in systems and "P1-nat" in systems:
        pairs = [(per_event[e]["L_P0-std"], per_event[e]["L_P1-nat"]) for e in strong
                 if per_event[e].get("L_P0-std") is not None and per_event[e].get("L_P1-nat") is not None]
        if len(pairs) >= 3:
            a, b = zip(*pairs)
            rho, p = spearmanr(a, b)
            result["screen"]["spearman_P0std_P1nat"] = {"rho": float(rho), "p": float(p), "n_events": len(pairs)}

    print("\n==== TIER-0 HETEROGENEITY SCREEN ====")
    for s, v in result["screen"].items():
        print(f"  {s}: {v}")
    if args.out:
        os.makedirs(os.path.dirname(args.out), exist_ok=True)
        json.dump(result, open(args.out, "w"), indent=2)
        print(f"\nwrote {args.out}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
